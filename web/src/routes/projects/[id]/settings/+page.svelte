<script lang="ts">
  import { api, errorMessage } from '$lib/api';
  import DeliverySettings from '$lib/components/DeliverySettings.svelte';
  import EnvSnippet from '$lib/components/EnvSnippet.svelte';
  import ProjectAccess from '$lib/components/ProjectAccess.svelte';
  import TokenManager from '$lib/components/TokenManager.svelte';
  import { session } from '$lib/session.svelte';
  import { fullDate, relativeTime } from '$lib/format';
  import type { Credential, IssuedCredential, TagRule } from '$lib/types';

  let { data } = $props();

  // Local copies, updated as the user creates and revokes things.
  let credentials = $state<Credential[]>([]);
  let rules = $state<TagRule[]>([]);
  let label = $state('');
  let issued = $state<IssuedCredential | null>(null);
  let selected = $state<number | null>(null);
  let busy = $state(false);
  let error = $state('');

  let ruleKind = $state<'header' | 'recipient'>('header');
  let ruleHeader = $state('');
  let rulePattern = $state('');
  let ruleTag = $state('');
  let ruleError = $state('');

  $effect(() => {
    credentials = data.credentials;
    rules = data.rules;
    issued = null;
    selected = null;
  });

  let active = $derived(credentials.filter((c) => !c.revoked_at));
  let shown = $derived(selected === null ? null : credentials.find((c) => c.id === selected) ?? null);

  async function create(event: SubmitEvent) {
    event.preventDefault();
    busy = true;
    error = '';
    try {
      const created = await api.createCredential(data.projectId, label);
      const { secret: _secret, ...stored } = created;
      credentials = [stored, ...credentials];
      issued = created;
      selected = null;
      label = '';
    } catch (e) {
      error = errorMessage(e);
    } finally {
      busy = false;
    }
  }

  async function revoke(c: Credential) {
    if (!confirm(`Revoke ${c.username}? Apps using it will stop being able to send.`)) return;
    error = '';
    try {
      await api.revokeCredential(data.projectId, c.id);
      credentials = credentials.map((x) => (x.id === c.id ? { ...x, revoked_at: new Date().toISOString() } : x));
      if (issued?.id === c.id) issued = null;
    } catch (e) {
      error = errorMessage(e);
    }
  }

  async function addRule(event: SubmitEvent) {
    event.preventDefault();
    ruleError = '';
    try {
      const rule = await api.createTagRule(data.projectId, {
        kind: ruleKind,
        header_name: ruleKind === 'header' ? ruleHeader : '',
        pattern: rulePattern,
        tag: ruleTag
      });
      rules = [...rules, rule];
      ruleHeader = rulePattern = ruleTag = '';
    } catch (e) {
      ruleError = errorMessage(e);
    }
  }

  async function removeRule(rule: TagRule) {
    ruleError = '';
    try {
      await api.deleteTagRule(data.projectId, rule.id);
      rules = rules.filter((r) => r.id !== rule.id);
    } catch (e) {
      ruleError = errorMessage(e);
    }
  }
</script>

<div class="page">
  <header>
    <h1>{data.project.name}</h1>
    <p class="muted">Project settings · <code>{data.project.slug}</code></p>
  </header>

  <section class="card stack" aria-labelledby="creds">
    <h2 id="creds">SMTP credentials</h2>
    <p class="muted">
      Each credential sends mail into this project only. Secrets are generated by the server and shown once.
      Use one credential per app or pipeline so you can revoke them independently.
    </p>

    <form class="row" onsubmit={create}>
      <label class="sr-only" for="cred-label">Label</label>
      <input id="cred-label" class="input" placeholder="Label, for example staging app" bind:value={label} maxlength="100" />
      <button class="btn primary" disabled={busy}>Create credential</button>
    </form>
    {#if error}<p class="error" role="alert">{error}</p>{/if}

    {#if issued}
      <div class="notice stack" role="status">
        <strong>Copy the secret now. It will not be shown again.</strong>
        <EnvSnippet info={data.info} username={issued.username} secret={issued.secret} />
      </div>
    {/if}

    {#if credentials.length === 0}
      <p class="muted">No credentials yet.</p>
    {:else}
      <table>
        <thead><tr><th>Username</th><th>Label</th><th>Created</th><th>Last used</th><th></th></tr></thead>
        <tbody>
          {#each credentials as c (c.id)}
            <tr class:revoked={c.revoked_at}>
              <td class="mono">{c.username}</td>
              <td>{c.label || '-'}</td>
              <td title={fullDate(c.created_at)}>{relativeTime(c.created_at)}</td>
              <td>{c.last_used_at ? relativeTime(c.last_used_at) : 'never'}</td>
              <td class="actions">
                {#if c.revoked_at}
                  <span class="badge danger">revoked</span>
                {:else}
                  <button type="button" class="btn small" onclick={() => (selected = selected === c.id ? null : c.id)}>
                    {selected === c.id ? 'Hide' : 'Env snippet'}
                  </button>
                  <button type="button" class="btn small danger" onclick={() => revoke(c)}>Revoke</button>
                {/if}
              </td>
            </tr>
          {/each}
        </tbody>
      </table>
      {#if shown}
        <div class="stack">
          <p class="muted">The password is not stored in readable form, so the snippet has a placeholder for it.</p>
          <EnvSnippet info={data.info} username={shown.username} />
        </div>
      {/if}
      {#if active.length === 0}<p class="muted">All credentials are revoked, nothing can send to this project.</p>{/if}
    {/if}
  </section>

  <section class="card stack" aria-labelledby="rules">
    <h2 id="rules">Tag rules</h2>
    <p class="muted">
      Applied to each new message. A header rule matches a header value, a recipient rule matches any
      recipient. <code>*</code> is a wildcard, an empty pattern matches anything. In a header rule, <code>{'{value}'}</code>
      in the tag is replaced by the header value, for example <code>X-Run-Id</code> with tag <code>run:{'{value}'}</code>.
    </p>
    <form class="row" onsubmit={addRule}>
      <select class="input" bind:value={ruleKind} aria-label="Rule kind">
        <option value="header">Header</option>
        <option value="recipient">Recipient</option>
      </select>
      {#if ruleKind === 'header'}
        <input class="input" placeholder="Header, X-Run-Id" bind:value={ruleHeader} aria-label="Header name" required />
      {/if}
      <input class="input" placeholder="Pattern (optional)" bind:value={rulePattern} aria-label="Pattern" />
      <input class="input" placeholder="Tag" bind:value={ruleTag} aria-label="Tag" required />
      <button class="btn">Add rule</button>
    </form>
    {#if ruleError}<p class="error" role="alert">{ruleError}</p>{/if}
    {#if rules.length > 0}
      <table>
        <thead><tr><th>Kind</th><th>Header</th><th>Pattern</th><th>Tag</th><th></th></tr></thead>
        <tbody>
          {#each rules as r (r.id)}
            <tr>
              <td>{r.kind}</td>
              <td class="mono">{r.header_name || '-'}</td>
              <td class="mono">{r.pattern || '(any)'}</td>
              <td class="mono">{r.tag}</td>
              <td><button type="button" class="btn small danger" onclick={() => removeRule(r)}>Delete</button></td>
            </tr>
          {/each}
        </tbody>
      </table>
    {/if}
  </section>

  {#key data.projectId}
    <DeliverySettings projectId={data.projectId} />
    <TokenManager
      id="project-tokens"
      heading="Project API tokens"
      intro="A project token is pinned to this project and never gets more than member access. Use it for CI and for Mailpit compatible clients. The secret is shown once, at creation. Prefix: spp_."
      scopes={['read', 'write']}
      load={() => api.listProjectTokens(data.projectId)}
      create={(input) => api.createProjectToken(data.projectId, input)}
      revoke={(t) => api.revokeProjectToken(data.projectId, t.id)}
    />
    <ProjectAccess projectId={data.projectId} isAdmin={session.user?.is_admin === true} />
  {/key}
</div>

